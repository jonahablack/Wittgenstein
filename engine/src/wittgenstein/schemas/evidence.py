"""EvidenceRecord and ExperimentalEnvelope.

ExperimentalEnvelope is deliberately reused in two roles:
1. Embedded in an EvidenceRecord, describing the setting a study actually tested.
2. Produced by `profiling/manifest_profile.py` from a PipelineManifest + CorpusProfile
   + QueryTrace, describing the setting a deployed system is actually running in.

Reusing one schema for both sides lets `matching/transferability.py` do a plain
field-by-field comparison instead of maintaining two parallel vocabularies that can
drift out of sync.
"""

from __future__ import annotations

from datetime import date

from pydantic import BaseModel, ConfigDict, Field, model_validator

from wittgenstein.core.enums import (
    ESTABLISHED_GRADE_FLOOR,
    EvidenceDirection,
    EvidenceGrade,
    PeerReviewStatus,
    QuoteType,
    StudyType,
    VerificationStatus,
)


class ExperimentalEnvelope(BaseModel):
    """Experimental preconditions/setting needed to assess transfer.

    Every field is optional at the type level because either side (a study's reported
    setting, or a manifest-derived setting) may not specify it -- but `None` must be
    read as "unknown," never coerced into a default. See docs/manifest-spec.md.
    """

    model_config = ConfigDict(extra="forbid")

    rag_presence: bool | None = None
    task_type: str | None = None
    question_structure: str | None = None
    domain: str | None = None
    corpus_size: str | None = None
    document_structure: str | None = None
    corpus_versioning: str | None = None
    retrieval_topology: str | None = None
    retriever_family: str | None = None
    embedding_family: str | None = None
    retrieval_unit: str | None = None
    chunking_method: str | None = None
    chunk_size_or_distribution: str | None = None
    overlap_or_stride: str | None = None
    candidate_depth: int | None = None
    rerank_depth: int | None = None
    reranker_family: str | None = None
    query_transformation: str | None = None
    parent_child_expansion: bool | None = None
    graph_retrieval: bool | None = None
    compression_type: str | None = None
    compression_ratio: float | None = None
    packing_method: str | None = None
    ordering_method: str | None = None
    packed_item_count: int | None = None
    context_window_tokens: int | None = None
    evidence_budget_tokens: int | None = None
    generator_family: str | None = None
    model_identifier: str | None = None
    prompting_policy: str | None = None
    citation_policy: str | None = None
    abstention_policy: str | None = None
    experimental_intervention: str | None = None

    def known_fields(self) -> dict[str, object]:
        return {k: v for k, v in self.model_dump().items() if v is not None}

    def unknown_field_names(self) -> list[str]:
        return [k for k, v in self.model_dump().items() if v is None]


class EvidenceRecord(BaseModel):
    """One paper/study's support for a mechanism.

    `exact_quote` must be verbatim from the primary source. It is never autogenerated
    or paraphrased -- if a quote has not yet been personally verified against the
    primary source, the seed convention is to leave the literal string
    "TODO: verify against primary source" here and set
    verification_status=UNVERIFIED, rather than inventing plausible-sounding text.
    """

    model_config = ConfigDict(extra="forbid")

    id: str
    failure_mechanism_id: str
    full_citation: str
    title: str
    authors: list[str]
    venue: str
    publication_year: int | None = Field(
        default=None, description="None only when the primary source itself is not yet confirmed."
    )
    peer_review_status: PeerReviewStatus
    persistent_identifier: str | None = Field(
        default=None, description="DOI, arXiv ID, or other persistent identifier."
    )
    source_url: str | None = None
    exact_quote: str
    quote_location: str = Field(..., description='Precise location, e.g. "Abstract", "Table 3", "Section 5.2".')
    quote_type: QuoteType
    study_type: StudyType
    direction: EvidenceDirection = Field(
        ...,
        description="Whether this record supports, refutes, or is mixed/null on its mechanism's "
        "causal claim. Required and never inferred -- see docs/registry-governance.md "
        '("Conflicting studies"). Contradictory records are kept as separate, independently '
        "directioned EvidenceRecords, never merged or averaged into one.",
    )
    task: str
    dataset_or_corpus: str
    experimental_envelope: ExperimentalEnvelope
    intervention_or_comparison: str
    outcome_metrics: list[str]
    effect_size_text: str | None = None
    statistical_evidence: str | None = None
    stated_limitations: str
    evidence_grade: EvidenceGrade
    extraction_reviewer: str
    extraction_date: date
    verification_status: VerificationStatus

    @model_validator(mode="after")
    def _verified_records_cannot_contain_todo(self) -> EvidenceRecord:
        if self.verification_status == VerificationStatus.VERIFIED:
            todo_fields = [
                name
                for name in ("exact_quote", "quote_location", "effect_size_text", "full_citation")
                if isinstance(getattr(self, name), str) and "TODO" in getattr(self, name)
            ]
            if todo_fields:
                raise ValueError(
                    "verification_status=verified but the following fields still contain "
                    f"a TODO placeholder: {todo_fields}. Verify against the primary source "
                    "first, or set verification_status=unverified."
                )
        return self

    @model_validator(mode="after")
    def _a_grade_requires_peer_review(self) -> EvidenceRecord:
        if self.evidence_grade in ESTABLISHED_GRADE_FLOOR and self.peer_review_status != (
            PeerReviewStatus.PEER_REVIEWED
        ):
            raise ValueError(
                f"evidence_grade={self.evidence_grade.value} requires peer_review_status=peer_reviewed."
            )
        return self

    def is_unverified_or_incomplete(self) -> bool:
        """True if this record must not support production activation of a mechanism."""

        if self.verification_status != VerificationStatus.VERIFIED:
            return True
        candidate_strings = [self.exact_quote, self.quote_location, self.full_citation]
        return any("TODO" in s for s in candidate_strings if isinstance(s, str))
